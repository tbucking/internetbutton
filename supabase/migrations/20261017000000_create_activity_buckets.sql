-- activity_buckets: one row per device per minute.
--
-- This migration records the schema already live in the Supabase project, so the
-- repo is self-contained. The definition and rationale are documented in
-- docs/ACTIVITY.md ("The cloud end").

create table public.activity_buckets (
  id           bigint generated by default as identity primary key,
  device_id    text not null,
  bucket_start timestamptz not null,
  impulses     integer not null,
  impulse_sum  bigint not null,
  max_delta    integer,          -- NULL when the firmware sent 0
  max_dz       integer,          -- NULL when 0; 255 means "at least 255"
  batch        integer not null default 0,
  received_at  timestamptz not null default now(),

  constraint activity_buckets_device_bucket_key unique (device_id, bucket_start)
);

create index activity_buckets_bucket_start_idx
  on public.activity_buckets (bucket_start desc);

-- RLS is enabled with no policies: anon and authenticated roles can read and
-- write nothing. Only the service role (used inside the ingest-activity Edge
-- Function) inserts. This is deliberate, not an oversight.
alter table public.activity_buckets enable row level security;
